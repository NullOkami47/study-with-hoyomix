// Generates the build identity that ships with every artefact.
//
// Two rules matter for release integrity:
//
//  1. A build must never claim a commit it was not built from. This script
//     previously fell back to a hardcoded historical SHA when
//     `git rev-parse HEAD` failed, which silently mislabelled every local
//     build. There is no such fallback any more: if the commit cannot be
//     resolved the build fails.
//
//  2. The deployment environment is an explicit build input. It is never
//     inferred from the origin hostname: the production Worker is served from
//     a *.workers.dev hostname, so a hostname heuristic reports production as
//     "staging".
//
// Usage:
//   node scripts/generate-build-info.mjs [--environment=production|staging|development]
//                                        [--allow-unknown]
//
// Environment variables:
//   BUILD_COMMIT  authoritative commit SHA; overrides Git resolution
//   BUILD_ENV     environment, unless --environment is given
import { execSync } from 'node:child_process'
import * as fs from 'node:fs'
import * as path from 'node:path'

const VALID_ENVIRONMENTS = ['production', 'staging', 'development']

const argv = process.argv.slice(2)

function flagValue(name) {
  const prefix = `--${name}=`
  const match = argv.find((argument) => argument.startsWith(prefix))
  return match ? match.slice(prefix.length).trim() : undefined
}

const allowUnknown = argv.includes('--allow-unknown')

// 1. An explicit BUILD_COMMIT is authoritative.
let commit = (process.env.BUILD_COMMIT || '').trim() || undefined
let commitSource = 'BUILD_COMMIT'

// 2. Otherwise ask Git for the real commit.
if (!commit) {
  try {
    commit = execSync('git rev-parse HEAD', { encoding: 'utf8' }).trim()
    commitSource = 'git rev-parse HEAD'
  } catch {
    commit = undefined
  }
}

// 3. Never substitute a historical SHA. A build that cannot identify itself
//    must not ship. Local development can opt into an explicit "unknown".
if (!commit) {
  if (allowUnknown) {
    commit = 'unknown'
    commitSource = 'explicit --allow-unknown'
    console.warn(
      'WARNING: build commit could not be resolved; writing "unknown" because --allow-unknown was passed.',
    )
    console.warn('WARNING: this must never be used for a release or production build.')
  } else {
    console.error('ERROR: could not determine the build commit.')
    console.error('  Set BUILD_COMMIT=<sha> explicitly, or make `git rev-parse HEAD` work.')
    console.error('  Refusing to fall back to a historical commit: a release artefact must identify itself.')
    process.exit(1)
  }
}

// 4. The environment is explicit, never derived from a hostname.
const environment = flagValue('environment') || (process.env.BUILD_ENV || '').trim() || 'development'
if (!VALID_ENVIRONMENTS.includes(environment)) {
  console.error(
    `ERROR: invalid build environment ${JSON.stringify(environment)}; expected one of ${VALID_ENVIRONMENTS.join(', ')}.`,
  )
  process.exit(1)
}

const buildTime = new Date().toISOString()
const data = { commit, buildTime, environment }

const jsonPath = path.resolve('workers/buildInfo.json')
fs.writeFileSync(jsonPath, JSON.stringify(data, null, 2) + '\n', 'utf8')

const tsPath = path.resolve('workers/buildInfo.ts')
const tsContent = `// Auto-generated by scripts/generate-build-info.mjs
// Commit: ${commit} (${commitSource})
// Environment: ${environment}
export interface BuildInfo {
  commit: string
  buildTime: string
  environment: 'staging' | 'production' | 'development'
}

export const BUILD_INFO: BuildInfo = {
  commit: ${JSON.stringify(commit)},
  buildTime: ${JSON.stringify(buildTime)},
  environment: ${JSON.stringify(environment)},
}

/**
 * Returns the build identity baked in at build time.
 *
 * The environment is deliberately *not* derived from the request origin: the
 * production Worker is served from a *.workers.dev hostname, so inferring
 * "staging" from the hostname would misreport every production deployment.
 */
export function getBuildInfo(): BuildInfo {
  return BUILD_INFO
}
`
fs.writeFileSync(tsPath, tsContent, 'utf8')
console.log(`Generated ${jsonPath} and ${tsPath} with commit ${commit} (${commitSource}) at ${buildTime} [${environment}]`)
